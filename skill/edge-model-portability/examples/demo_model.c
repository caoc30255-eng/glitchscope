/* C99 implementation: reads the same frozen model file as Python. No device IO. */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <math.h>
#include <errno.h>
typedef struct { long max,w,g; double left,right,gl,gr; } Model;
static int load_model(const char *path,Model *m){
 FILE *f=fopen(path,"r");char header[64],extra[128];int n;
 if(!f)return 0;
 if(!fgets(header,sizeof(header),f)||strcmp(header,"SKILL_STUMPS_V1\n")){fclose(f);return 0;}
 n=fscanf(f,"max_feature=%ld\nthreshold_width=%ld\nthreshold_gap=%ld\nleft_score=%lf\nright_score=%lf\ngap_left_delta=%lf\ngap_right_delta=%lf",&m->max,&m->w,&m->g,&m->left,&m->right,&m->gl,&m->gr);
 if(n!=7){fclose(f);return 0;}
 while(fgets(extra,sizeof(extra),f)){size_t i;for(i=0;extra[i];++i)if(extra[i]!=' '&&extra[i]!='\r'&&extra[i]!='\n'&&extra[i]!='\t'){fclose(f);return 0;}}
 fclose(f);
 if(m->max<1||m->max>100000||m->w<0||m->w>m->max||m->g<0||m->g>m->max||!isfinite(m->left)||!isfinite(m->right)||!isfinite(m->gl)||!isfinite(m->gr))return 0;
 {double a[2]={m->left,m->right},b[2]={m->gl,m->gr};int i,j;for(i=0;i<2;i++)for(j=0;j<2;j++)if(!(a[i]+b[j]>0&&a[i]+b[j]<1))return 0;}
 return 1;
}
static int integer(const char *s,long *v){char *end;errno=0;*v=strtol(s,&end,10);return errno==0&&*s&&!*end;}
int main(int argc,char **argv){
 Model m;char line[256],id[32],xs[64],ys[64],extra[8];long x,y;int n;
 if(argc!=2||!load_model(argv[1],&m)){fprintf(stderr,"MODEL_LOAD_FAILED\n");return 2;}
 while(fgets(line,sizeof(line),stdin)){
  n=sscanf(line,"%31s %63s %63s %7s",id,xs,ys,extra);
  if(n!=3){fprintf(stderr,"INPUT_FORMAT\n");return 3;}
  /* IDs are generated by the wrapper, not arbitrary strings interpolated into JSON. */
  {size_t i;for(i=0;id[i];i++)if((id[i]<'0'||id[i]>'9')&&id[i]!='q'){fprintf(stderr,"INPUT_ID\n");return 3;}}
  if(!integer(xs,&x)||!integer(ys,&y)||x<0||y<0||x>m.max||y>m.max){
   printf("{\"id\":\"%s\",\"result\":{\"action\":\"ABSTAIN\",\"score\":null,\"uncertainty_entropy\":null,\"execution_allowed\":false}}\n",id);
  }else{
   double score=(x<=m.w?m.left:m.right)+(y<=m.g?m.gl:m.gr);
   double entropy=-(score*log2(score)+(1-score)*log2(1-score));
   printf("{\"id\":\"%s\",\"result\":{\"action\":\"PREDICT\",\"score\":%.17e,\"uncertainty_entropy\":%.17e,\"execution_allowed\":false}}\n",id,score,entropy);
  }
 }
 return ferror(stdin)?3:0;
}
